CATEGORIES = sorted({d["category"] for d in PLANT_DATABASES})


def search_databases(keyword: str = "", category: str = "", limit: int = 300) -> list[dict]:
    """按关键词/分类检索本地植物数据库目录。"""
    kw = (keyword or "").strip().lower()
    items = PLANT_DATABASES
    if category and category != "全部":
        items = [d for d in items if d["category"] == category]
    if kw:
        def hit(d: dict) -> bool:
            hay = " ".join(
                [d["name"], d.get("cn", ""), d.get("desc", ""), d.get("category", ""), " ".join(d.get("tags", []))]
            ).lower()
            return kw in hay

        items = [d for d in items if hit(d)]
    # 常用条目优先，其次名称完全匹配、名称包含，最后描述命中
    def rank(d: dict) -> tuple:
        n = d["name"].lower()
        if not kw and d.get("featured"):
            return (-1, d["name"])
        if kw and n == kw:
            return (0, d["name"])
        if kw and n.startswith(kw):
            return (1, d["name"])
        if kw and kw in n:
            return (2, d["name"])
        return (3, d["name"])

    return sorted(items, key=rank)[:limit]
