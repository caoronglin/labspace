import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const BASE='http://192.0.2.10';
const l=readFileSync('/etc/labspace/casdoor-users.txt','utf8').split('\n').find(x=>x.startsWith('labadmin@local '));
const [u,p]=l.trim().split(/\s+/);
const b=await chromium.launch({args:['--no-sandbox']});
const c=await b.newContext({viewport:{width:1440,height:1000},locale:'zh-CN'});
const page=await c.newPage();
const bad=[];
page.on('response',r=>{ if(r.status()>=400) bad.push(`${r.status()} ${r.request().method()} ${new URL(r.url()).pathname}`); });
await page.goto(BASE+'/login',{waitUntil:'domcontentloaded'});
await page.waitForSelector('input[type="password"]');
await page.locator('input[type="text"], input:not([type])').first().fill(u);
await page.locator('input[type="password"]').first().fill(p);
await page.getByRole('button',{name:/登录|Login/}).first().click();
await page.waitForTimeout(3500);
await page.goto(BASE+'/translation',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(2500);
for (let i=0;i<3;i+=1){ if(!(await page.locator('.ant-modal-wrap').count())) break; await page.keyboard.press('Escape'); await page.waitForTimeout(300); await page.locator('.ant-modal-close').first().click({timeout:1000}).catch(()=>{}); await page.waitForTimeout(300); }
console.log('BAD_AFTER_LOAD', JSON.stringify([...new Set(bad)]));
console.log('STATUS_TAGS', JSON.stringify(await page.locator('.ant-tag').allInnerTexts()));
const ta = page.locator('textarea').first();
await ta.fill('The CRISPR-Cas9 system enables targeted genome editing in plant cells.');
await page.getByRole('button',{name:/翻\s*译/}).last().click();
await page.waitForTimeout(30000);
const out = await page.locator('.ant-card').nth(1).innerText().catch(()=> '');
console.log('RESULT_CARD', JSON.stringify(out.replace(/\s+/g,' ').slice(0,200)));
console.log('BAD_AFTER_TRANSLATE', JSON.stringify([...new Set(bad)]));
await page.screenshot({path:'/opt/labspace/e2e/shots/translation-live.png'});
await b.close();
