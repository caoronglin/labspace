import fs from 'node:fs';
import { chromium } from 'playwright';
const BASE='http://192.0.2.10';
const line = fs.readFileSync('/etc/labspace/casdoor-users.txt','utf8').split('\n').find(l=>l.trimStart().startsWith('labadmin@local'));
const pw = line.trim().split(/\s+/)[1];
const b = await chromium.launch({args:['--no-sandbox']});
const ctx = await b.newContext({locale:'zh-CN',viewport:{width:1680,height:1000}});
const page = await ctx.newPage();
await page.goto(BASE+'/login',{waitUntil:'domcontentloaded'});
await page.waitForSelector('input[type="password"]');
await page.locator('input[type="text"], input:not([type])').first().fill('labadmin');
await page.locator('input[type="password"]').first().fill(pw);
await page.getByRole('button',{name:/登录|Login/}).first().click();
await page.waitForTimeout(5000);
await page.goto(BASE+'/',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(3000);
const aria = await page.evaluate(()=>Array.from(document.querySelectorAll('[aria-label]')).map(e=>e.getAttribute('aria-label')).filter(Boolean).slice(0,40));
console.log('ARIA:', JSON.stringify(aria,null,0).slice(0,900));
const tiles = await page.evaluate(()=>Array.from(document.querySelectorAll('.d509-tile')).map(e=>e.getAttribute('aria-label')+' | '+e.innerText.replace(/\s+/g,' ').slice(0,30)));
console.log('TILES:', JSON.stringify(tiles,null,0).slice(0,800));
// now the avatar menu
await page.locator('.ant-layout-header .ant-avatar').first().click();
await page.waitForTimeout(1000);
console.log('dropdowns:', await page.locator('.ant-dropdown').count(), 'menu items:', await page.locator('.ant-dropdown-menu-item').count());
const items = await page.evaluate(()=>Array.from(document.querySelectorAll('.ant-dropdown-menu-item')).map(e=>({t:e.innerText, vis: !e.closest('.ant-dropdown-hidden')})));
console.log('ITEMS:', JSON.stringify(items));
await page.locator('.ant-dropdown:not(.ant-dropdown-hidden) .ant-dropdown-menu-item:has-text("个人资料")').first().click();
await page.waitForTimeout(1500);
console.log('modals:', await page.locator('.ant-modal-content').count());
console.log('modal text:', (await page.evaluate(()=>Array.from(document.querySelectorAll('.ant-modal-content')).map(e=>e.innerText.replace(/\s+/g,' ').slice(0,200)))));
await ctx.close(); await b.close();
