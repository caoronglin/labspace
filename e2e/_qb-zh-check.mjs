import { chromium } from 'playwright';
const browser = await chromium.launch();
const ctx = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
await page.goto('http://192.0.2.10:8080/files/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(2500);
const title = await page.title();
const txt = (await page.locator('body').innerText()).replace(/\s+/g, ' ').slice(0, 400);
const cjk = (txt.match(/[\u4e00-\u9fa5]/g) || []).length;
const latin = (txt.match(/[A-Za-z]{2,}/g) || []).length;
console.log('title:', title);
console.log('文本片段:', txt);
console.log(`中文字符=${cjk} 英文词=${latin}`);
await page.screenshot({ path: '/opt/labspace/e2e/shots/quantum-zh.png' });
await browser.close();
