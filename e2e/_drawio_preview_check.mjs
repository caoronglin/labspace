import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = 'http://192.0.2.10';
const line = fs.readFileSync('/etc/labspace/casdoor-users.txt', 'utf8').split('\n').find((l) => l.startsWith('labadmin@local'));
const pw = line.trim().split(/\s+/)[1];
let fails = 0;
const ok = (n, c, x = '') => { console.log(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  ' + x : ''}`); if (!c) fails++; };
const b = await chromium.launch({ args: ['--no-sandbox'] });
const ctx = await b.newContext({ locale: 'zh-CN', viewport: { width: 1680, height: 1000 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
await p.goto(`${BASE}/login`); await p.waitForSelector('input[type="password"]');
await p.locator('input[type="text"], input:not([type])').first().fill('labadmin');
await p.locator('input[type="password"]').first().fill(pw);
await p.getByRole('button', { name: /登录|Login/ }).first().click(); await p.waitForTimeout(4000);
const wm = p.locator('.ant-modal').filter({ hasText: '欢迎使用 D509 工作台' }).first();
if (await wm.isVisible().catch(() => false)) { await wm.getByRole('button', { name: /开始使用/ }).click(); await p.waitForTimeout(500); }
await p.goto(`${BASE}/drawio`, { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(5000);
const frame = p.frameLocator('iframe').first();
await p.getByRole('button', { name: /RNA-seq Pipeline/ }).click(); await p.waitForTimeout(2500);
await p.getByRole('button', { name: /预览图片/ }).click(); await p.waitForTimeout(4000);
const img = p.locator('.ant-modal img').first();
const src = await img.getAttribute('src').catch(() => null);
const nat = await img.evaluate((el) => ({ w: el.naturalWidth, h: el.naturalHeight })).catch(() => ({ w: 0, h: 0 }));
ok('预览弹窗出现', await img.isVisible().catch(() => false));
ok('预览为 SVG DataURL', !!src && src.startsWith('data:image/svg'), src ? `${Math.round(src.length / 1024)}KB` : 'none');
ok('图片有实际像素', nat.w > 300 && nat.h > 30, `${nat.w}x${nat.h}`);
ok('无前端异常', errs.length === 0, errs.slice(0, 2).join(' '));
await p.screenshot({ path: 'shots/final-drawio-preview.png', fullPage: false });
await b.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASS');
process.exit(fails ? 1 : 0);