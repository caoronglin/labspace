import { chromium } from 'playwright';
const BASE='http://192.0.2.10';
const browser=await chromium.launch({args:['--no-sandbox']});
const ctx=await browser.newContext({locale:'zh-CN'});
const page=await ctx.newPage();
await page.goto(`${BASE}/login`,{waitUntil:'domcontentloaded'});
await page.waitForSelector('input[type="password"]',{timeout:20000});
await page.locator('input[type="text"], input:not([type])').first().fill('student01');
await page.locator('input[type="password"]').first().fill(process.env.LAB_PASS);
await page.getByRole('button',{name:/登录|Login/}).first().click();
await page.waitForTimeout(5000);
const t0=Date.now();
const res=await page.evaluate(async()=>{const r=await fetch('/api/search?q=rice&scope=local&categories=general',{credentials:'include'});return{status:r.status,text:await r.text()}});
const ms=Date.now()-t0;
const body=JSON.parse(res.text);
console.log('status',res.status,'ms',ms);
console.log('databases',JSON.stringify(body.databases,null,1));
console.log('warnings',JSON.stringify(body.databaseWarnings));
await ctx.close();await browser.close();
