import fs from 'node:fs';
import { chromium } from 'playwright';
const BASE = process.env.LAB_BASE || 'http://192.0.2.10';
const line = fs.readFileSync('/etc/labspace/casdoor-users.txt','utf8').split('\n').find(l=>l.startsWith('labadmin@local'));
const [user,pass] = line.trim().split(/[: ]+/).filter(Boolean);
const b = await chromium.launch({args:['--no-sandbox']});
const ctx = await b.newContext({locale:'zh-CN'});
const p = await ctx.newPage();
await p.goto(`${BASE}/login`,{waitUntil:'domcontentloaded'});
await p.waitForSelector('input[type="password"]',{timeout:20000});
await p.locator('input[type="text"], input:not([type])').first().fill(user);
await p.locator('input[type="password"]').first().fill(pass);
await p.getByRole('button',{name:/登录|Login/}).first().click();
await p.waitForTimeout(5000);
await p.goto(`${BASE}/aikit`,{waitUntil:'domcontentloaded'});
await p.waitForTimeout(3000);
console.log('URL:', p.url());
console.log('BODY:', (await p.evaluate(()=>document.body.innerText)).slice(0,500).replace(/\n+/g,' | '));
await b.close();
