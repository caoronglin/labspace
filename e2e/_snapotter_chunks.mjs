import { chromium } from 'playwright';
const BASE = 'http://192.0.2.10:8092';
const pass = process.env.SO_PASS || '';
const browser = await chromium.launch();
const context = await browser.newContext({ locale: 'en-US', viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
const urls = new Set();
page.on('request', (r) => { if (r.resourceType() === 'script') urls.add(r.url()); });
await page.goto(BASE + '/login', { waitUntil: 'networkidle' });
await page.locator('input[type=text], input[type=email], input[name=username]').first().fill('admin');
await page.locator('input[type=password]').first().fill(pass);
await page.locator('input[type=password]').first().press('Enter');
await page.waitForTimeout(3000);
for (const u of urls) if (!/login/.test(u)) console.log(u.split('/').pop());
await browser.close();
