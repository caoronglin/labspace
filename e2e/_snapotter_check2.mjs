import { chromium } from 'playwright';
const BASE = 'http://192.0.2.10:8092';
const user = process.env.SO_USER || 'admin';
const pass = process.env.SO_PASS || '';
const browser = await chromium.launch();
const context = await browser.newContext({ locale: 'en-US', viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
await page.goto(BASE + '/login', { waitUntil: 'networkidle' });
await page.waitForTimeout(800);
await page.locator('input[type=text], input[type=email], input[name=username]').first().fill(user);
await page.locator('input[type=password]').first().fill(pass);
await page.locator('input[type=password]').first().press('Enter');
await page.waitForTimeout(2500);
console.log('AFTER LOGIN URL:', page.url());
const body = (await page.locator('body').innerText()).replace(/\s+/g, ' ');
console.log('HAS_EN_TOOL:', /Remove GIF Background|Sign PDF/.test(body));
console.log('BODY:', body.slice(0, 400));
await page.screenshot({ path: 'shots/_snapotter_cn.png', fullPage: false });
await page.goto(BASE + '/remove-gif-background', { waitUntil: 'networkidle' }).catch(()=>{});
await page.waitForTimeout(1200);
console.log('TOOL URL:', page.url());
console.log('TOOL BODY:', (await page.locator('body').innerText()).replace(/\s+/g, ' ').slice(0, 300));
await page.screenshot({ path: 'shots/_snapotter_gif.png', fullPage: false });
await browser.close();
