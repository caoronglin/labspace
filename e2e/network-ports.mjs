import { chromium } from 'playwright';
const BASE = process.env.BASE || 'http://127.0.0.1';
const b = await chromium.launch({args:['--no-sandbox']});
const ctx = await b.newContext({locale:'zh-CN', viewport:{width:1500,height:1000}});
const p = await ctx.newPage();
await p.goto(`${BASE}/login`, {waitUntil:'domcontentloaded'});
await p.waitForTimeout(3500);
await p.waitForSelector('input[type="password"]', {timeout:15000});
await p.locator('input[type="text"], input:not([type])').first().fill('student01');
await p.locator('input[type="password"]').first().fill(process.env.LAB_PASS);
await p.getByRole('button', {name:/登录|Login/}).first().click();
await p.waitForTimeout(6000);
await p.goto(`${BASE}/network`, {waitUntil:'networkidle'});
await p.waitForTimeout(2500);
const t=(await p.evaluate(()=>document.body.innerText)).replace(/\s+/g,' ');
console.log('  含域名残留:', /lab\.internal/.test(t) ? '有 ✗' : '无 ✓');
console.log('  入口自检:', (t.match(/全部入口探测正常|\d+ 个入口异常/)||[])[0]);
const HOST = process.env.LAB_HOST || '127.0.0.1';
console.log('  端口清单:', ['8090','8080','8082','8084','8086','8091','8102'].map(p => `${HOST}:${p}`).filter(x => t.includes(x)).join(' '));
await p.screenshot({path:'/opt/labspace/e2e/shots/network-ports.png'});
await b.close();
